<?php

namespace App\Services\Data;

use App\Enums\BillType;
use App\Models\Device;
use App\Models\User;

/**
 * Everything the till sends for one checkout. Prices are NOT accepted from the
 * client; they are always read from the server's price list.
 */
final readonly class CheckoutData
{
    /**
     * @param  list<CartLine>  $lines
     * @param  list<PaymentInput>  $payments
     */
    public function __construct(
        public Device $device,
        public User $cashier,
        public array $lines,
        public array $payments,
        public int $saleDiscount = 0,         // whole-sale discount, minor units
        public ?string $uuid = null,          // generated by the till; makes retries/sync safe
        public ?string $customerName = null,
        public ?string $customerPhone = null,
        public ?string $notes = null,
        // Sale already happened at the till: never block on stock or the discount limit.
        // SECURITY: only set this from the authenticated device-sync endpoint, never from request input.
        public bool $isOfflineSync = false,
        public ?\DateTimeInterface $soldAt = null,
        public ?string $invoiceNo = null,     // offline tills number their own invoices
        // What an offline till worked out and charged, so the server records the sale
        // the customer actually paid for and flags any difference for the owner.
        public ?int $tillGrandTotal = null,
        public ?float $tillTaxRate = null,
        public ?bool $tillPricesIncludeTax = null,
        // An OPD bill (an OPD till): the consultation plus one Medicines amount
        // (minor units) spread over the medicine lines.
        public BillType $billType = BillType::Standard,
        public ?int $opdMedicinesAmount = null,
        // Offline: the till's clock minus the server's at upload, in seconds
        // (positive = the till is ahead); null online and for older clients.
        public ?int $clockOffsetSeconds = null,
    ) {}
}
